import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "server/src/config/vercelApp.bundle.mjs");

await build({
  entryPoints: [join(root, "server/src/vercelApp.ts")],
  outfile: output,
  bundle: true,
  format: "esm",
  platform: "node",
  packages: "external",
  sourcemap: false,
  target: "node24",
  logLevel: "warning",
  banner: { js: "// Generated by scripts/build-vercel-api.mjs. Do not edit." },
});

if (!process.argv.includes("--verify")) process.exit(0);

const scratch = await mkdtemp(join(tmpdir(), "chelcoach-vercel-api-"));
let server;
try {
  await mkdir(join(scratch, "api"), { recursive: true });
  await writeFile(join(scratch, "package.json"), '{"type":"module"}\n');
  await symlink(join(root, "server"), join(scratch, "server"), "dir");

  const entrySource = await readFile(join(root, "api/index.ts"), "utf8");
  const emitted = ts.transpileModule(entrySource, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      target: ts.ScriptTarget.ES2023,
    },
    fileName: "api/index.ts",
  }).outputText;
  await writeFile(join(scratch, "api/index.js"), emitted);

  process.env.NODE_ENV = "test";
  process.env.CHELCOACH_SKIP_CONFIG_VALIDATION = "1";
  process.env.CHELCOACH_FORCE_MEMORY_REPOS = "1";
  process.env.CHELCOACH_SKIP_PROVIDER_VALIDATION = "1";

  const { default: app } = await import(pathToFileURL(join(scratch, "api/index.js")));
  assert.equal(typeof app, "function", "Vercel entrypoint must export the Express app");

  server = createServer(app);
  await new Promise((resolveListen, rejectListen) => {
    server.once("error", rejectListen);
    server.listen(0, "127.0.0.1", resolveListen);
  });
  const address = server.address();
  assert(address && typeof address === "object");
  const response = await fetch(`http://127.0.0.1:${address.port}/api/health`);
  assert.equal(response.status, 200, "bundled Express health route must return HTTP 200");
  assert.match(response.headers.get("content-type") ?? "", /application\/json/);
  const body = await response.json();
  assert.equal(body.status, "ok", "bundled Express health route must report ok");
  console.log("Vercel API bundle boot verification passed (GET /api/health: 200 ok)");
} finally {
  if (server) await new Promise((resolveClose) => server.close(resolveClose));
  await rm(scratch, { recursive: true, force: true });
}
